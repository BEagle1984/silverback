using System;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Silverback.Tools.Generators.LogEvents;

/// <summary>
///     Generates the public <c>LogEvent</c> properties from the <c>[LoggerMessage]</c> methods declared in the
///     <c>*LoggerExtensions</c> classes, so that each log event is defined in a single place.
/// </summary>
/// <remarks>
///     The logging methods are generated by the Microsoft.Extensions.Logging generator, which reads the same declarations.
///     Generators can't see each other's output, so the two of them can't be chained.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class LogEventsGenerator : IIncrementalGenerator
{
    private const string LoggerMessageAttributeName = "Microsoft.Extensions.Logging.LoggerMessageAttribute";

    private const string LoggerExtensionsSuffix = "LoggerExtensions";

    private const string LogEventsSuffix = "LogEvents";

    private static readonly string[] LogLevels = ["Trace", "Debug", "Information", "Warning", "Error", "Critical", "None"];

    private static readonly DiagnosticDescriptor InvalidLoggerMessage = new(
        "SILVERBACK001",
        "Incomplete log event definition",
        "The [LoggerMessage] attribute of '{0}' must specify the event id, level, message and event name",
        "Silverback.LogEvents",
        DiagnosticSeverity.Error,
        true);

    /// <inheritdoc cref="IIncrementalGenerator.Initialize" />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<LogEventModel> models = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                LoggerMessageAttributeName,
                static (node, _) => node is MethodDeclarationSyntax,
                static (attributeContext, _) => CreateModel(attributeContext))
            .Where(static model => model != null)!;

        context.RegisterSourceOutput(models.Collect(), static (output, collectedModels) => Generate(output, collectedModels));
    }

    private static LogEventModel? CreateModel(GeneratorAttributeSyntaxContext context)
    {
        INamedTypeSymbol containingType = context.TargetSymbol.ContainingType;

        if (!containingType.Name.EndsWith(LoggerExtensionsSuffix, StringComparison.Ordinal))
            return null;

        AttributeData attribute = context.Attributes[0];
        int? eventId = GetArgument<int?>(attribute, nameof(LogEventModel.EventId));
        int? level = GetArgument<int?>(attribute, nameof(LogEventModel.Level));
        string? message = GetArgument<string>(attribute, nameof(LogEventModel.Message));
        string? eventName = GetArgument<string>(attribute, nameof(LogEventModel.EventName));

        if (eventId == null || level == null || message == null || eventName == null)
            return new LogEventModel(context.TargetSymbol.Name, context.TargetNode.GetLocation());

        return new LogEventModel(context.TargetSymbol.Name)
        {
            Namespace = containingType.ContainingNamespace.ToDisplayString(),
            ClassName = containingType.Name.Substring(0, containingType.Name.Length - LoggerExtensionsSuffix.Length) + LogEventsSuffix,
            EventId = eventId.Value,
            EventName = eventName,
            Level = level.Value,
            Message = message,
            Documentation = GetDocumentation(context.TargetNode),
            Usings = string.Join("\n", context.TargetNode.SyntaxTree.GetCompilationUnitRoot().Usings.Select(item => item.ToString()))
        };
    }

    private static T? GetArgument<T>(AttributeData attribute, string name)
    {
        foreach (System.Collections.Generic.KeyValuePair<string, TypedConstant> argument in attribute.NamedArguments)
        {
            if (argument.Key == name)
                return (T?)argument.Value.Value;
        }

        ImmutableArray<IParameterSymbol> parameters = attribute.AttributeConstructor?.Parameters ?? [];

        for (int i = 0; i < parameters.Length; i++)
        {
            if (string.Equals(parameters[i].Name, name, StringComparison.OrdinalIgnoreCase))
                return (T?)attribute.ConstructorArguments[i].Value;
        }

        return default;
    }

    // The raw text is copied, so that the crefs are resolved against the usings copied from the same file
    private static string GetDocumentation(SyntaxNode node)
    {
        StringBuilder builder = new();

        foreach (SyntaxTrivia trivia in node.GetLeadingTrivia().Where(static trivia => trivia.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)))
        {
            foreach (string line in trivia.ToFullString().Split('\n'))
            {
                string trimmedLine = line.Trim();

                if (trimmedLine.Length == 0)
                    continue;

                builder.Append("    ");
                builder.Append(trimmedLine.StartsWith("///", StringComparison.Ordinal) ? trimmedLine : "/// " + trimmedLine);
                builder.Append('\n');
            }
        }

        return builder.ToString();
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<LogEventModel> models)
    {
        foreach (LogEventModel model in models.Where(static model => model.Location != null))
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidLoggerMessage, model.Location, model.Name));
        }

        foreach (IGrouping<string, LogEventModel> modelsGroup in models.Where(static model => model.Location == null).GroupBy(static model => model.ClassName))
        {
            context.AddSource($"{modelsGroup.Key}.g.cs", SourceText.From(GenerateClass(modelsGroup), Encoding.UTF8));
        }
    }

    private static string GenerateClass(IGrouping<string, LogEventModel> models)
    {
        LogEventModel firstModel = models.First();
        StringBuilder builder = new();

        builder.Append("// <auto-generated/>\n");
        builder.Append("#nullable enable\n\n");
        builder.Append(firstModel.Usings).Append("\n\n");
        builder.Append("namespace ").Append(firstModel.Namespace).Append(";\n\n");
        builder.Append("public static partial class ").Append(models.Key).Append("\n{\n");

        foreach (LogEventModel model in models)
        {
            builder.Append(model.Documentation);
            builder.Append("    public static global::Silverback.Diagnostics.LogEvent ").Append(model.Name).Append(" { get; } = new(\n");
            builder.Append("        global::Microsoft.Extensions.Logging.LogLevel.").Append(LogLevels[model.Level]).Append(",\n");
            builder.Append("        new global::Microsoft.Extensions.Logging.EventId(");
            builder.Append(model.EventId.ToString(CultureInfo.InvariantCulture)).Append(", ");
            builder.Append(SymbolDisplay.FormatLiteral(model.EventName, true)).Append("),\n");
            builder.Append("        ").Append(SymbolDisplay.FormatLiteral(model.Message, true)).Append(");\n\n");
        }

        builder.Append("}\n");

        return builder.ToString();
    }
}
