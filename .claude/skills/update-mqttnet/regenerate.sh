#!/usr/bin/env bash
# Regenerates the MQTT configuration proxies and runs the code cleanup on them.
# Usage (from the repository root, Git Bash): .claude/skills/update-mqttnet/regenerate.sh [output-dir]
# The raw generator output is kept in output-dir (default: a temp folder) to diff it against previous runs.
set -euo pipefail

generator=tools/Silverback.Tools.Generators.MqttConfigProxies
mqtt_file=src/Silverback.Integration.MQTT/Messaging/Configuration/Mqtt/_autogenerated.cs
output_dir=${1:-"${TEMP:-/tmp}/silverback-mqtt-proxies"}

mkdir -p "$output_dir"

# Built separately so that compile errors are shown (dotnet run writes them to stdout, i.e. into the output file)
dotnet build "$generator" -c Release --verbosity quiet
dotnet run --project "$generator" -c Release --no-build > "$output_dir/mqtt.cs"

# Keeps the hand-written file header (everything before the first generated type) and replaces the rest
first_line=$(grep -n -m1 "^/// <content>" "$mqtt_file" | cut -d: -f1)
{ head -n $((first_line - 1)) "$mqtt_file"; cat "$output_dir/mqtt.cs"; } > "$mqtt_file.tmp"
mv "$mqtt_file.tmp" "$mqtt_file"

# Without a restore (e.g. in a fresh worktree) the cleanup can't resolve the library types and silently rewrites the files (qualified type names, dropped usings)
dotnet restore Silverback.slnx --verbosity quiet

# --no-build: the solution may not compile yet (missing partial declarations), the cleanup doesn't need it
dotnet tool restore > /dev/null
dotnet jb cleanupcode Silverback.slnx \
    --profile="Silverback: Full Cleanup" \
    --no-build \
    --include="src/Silverback.Integration.MQTT/**/_autogenerated.cs" \
    > "$output_dir/cleanup.log" 2>&1 || { echo "Cleanup failed, see $output_dir/cleanup.log"; exit 1; }

echo "Proxies regenerated and cleaned up (raw output in $output_dir)"
