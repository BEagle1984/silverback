#!/usr/bin/env bash
# Regenerates the Kafka and schema registry configuration proxies and runs the code cleanup on them.
# Usage (from the repository root, Git Bash): .claude/skills/update-confluent-kafka/regenerate.sh [output-dir]
# The raw generator output is kept in output-dir (default: a temp folder) to diff it against previous runs.
set -euo pipefail

generator=tools/Silverback.Tools.Generators.KafkaConfigProxies
kafka_file=src/Silverback.Integration.Kafka/Messaging/Configuration/Kafka/_autogenerated.cs
schema_registry_file=src/Silverback.Integration.Kafka.SchemaRegistry/Messaging/Configuration/Kafka/SchemaRegistry/_autogenerated.cs
output_dir=${1:-"${TEMP:-/tmp}/silverback-kafka-proxies"}

mkdir -p "$output_dir"

dotnet run --project "$generator" -c Release > "$output_dir/kafka.cs"
dotnet run --project "$generator" -c Release --no-build -- --schemaregistry > "$output_dir/schema-registry.cs"

# Keeps the hand-written file header (everything before the first generated type) and replaces the rest
splice() {
    local file=$1 generated=$2
    local first_line
    first_line=$(grep -n -m1 "^/// <content>" "$file" | cut -d: -f1)
    { head -n $((first_line - 1)) "$file"; cat "$generated"; } > "$file.tmp"
    mv "$file.tmp" "$file"
}

splice "$kafka_file" "$output_dir/kafka.cs"
splice "$schema_registry_file" "$output_dir/schema-registry.cs"

# --no-build: the solution may not compile yet (missing partial declarations), the cleanup doesn't need it
dotnet tool restore > /dev/null
dotnet jb cleanupcode Silverback.sln \
    --profile="Silverback: Full Cleanup" \
    --no-build \
    --include="src/Silverback.Integration.Kafka*/**/_autogenerated.cs" \
    > "$output_dir/cleanup.log" 2>&1 || { echo "Cleanup failed, see $output_dir/cleanup.log"; exit 1; }

echo "Proxies regenerated and cleaned up (raw output in $output_dir)"
