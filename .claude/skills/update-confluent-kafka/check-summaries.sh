#!/usr/bin/env bash
# Compares the summary of each builder WithX method with the summary of the matching proxied property X
# and prints the pairs whose first words differ (ignoring the "Gets"/"Sets" prefix and markup).
# Usage (from the repository root, Git Bash): .claude/skills/update-confluent-kafka/check-summaries.sh
set -euo pipefail

extract() {
    tr -d '\r' < "$1" | awk '
        /\/\/\/ <summary>/ { insum = 1; text = ""; next }
        /\/\/\/ <\/summary>/ { insum = 0; next }
        insum { line = $0; sub(/^ *\/\/\/ */, "", line); text = text " " line; next }
        /^ *\/\/\// || /^ *\[/ { next }
        /^ *(public|internal)[^(]* [A-Za-z]+ \{ get; init; \}/ {
            name = $0; sub(/ \{.*/, "", name); sub(/.* /, "", name)
            if (text != "") print "P|" name "|" text
        }
        /^ *(public|internal)( partial)? [A-Za-z<>]+ With[A-Za-z]+\(/ {
            name = $0; sub(/\(.*/, "", name); sub(/.* With/, "", name)
            if (text != "") print "W|" name "|" text
        }
        { text = "" }'
}

normalize() {
    sed -E 's/^ *(Gets|Sets|Specifies) +(a value indicating )?(the )?//I; s/<see cref="[^"]*"[^>]*>//g; s/<[^>]+>//g; s/[^A-Za-z0-9]+/ /g' |
        tr '[:upper:]' '[:lower:]' | cut -c1-60
}

compare() {
    local summaries
    summaries=$(for file in "$@"; do extract "$file"; done)

    grep "^W|" <<< "$summaries" | sort -u | while IFS='|' read -r _ name builder_summary; do
        property_summary=$(grep "^P|$name|" <<< "$summaries" | head -1 | cut -d'|' -f3 || true)
        [ -z "$property_summary" ] && continue

        if [ "$(normalize <<< "$builder_summary")" != "$(normalize <<< "$property_summary")" ]; then
            printf '%s\n  With: %s\n  Prop: %s\n' "$name" "$builder_summary" "$property_summary"
        fi
    done
}

kafka=src/Silverback.Integration.Kafka/Messaging/Configuration/Kafka
schema_registry=src/Silverback.Integration.Kafka.SchemaRegistry/Messaging/Configuration/Kafka/SchemaRegistry

echo "### Kafka"
compare "$kafka/_autogenerated.cs" "$kafka"/KafkaClientConfigurationBuilder\`1.cs "$kafka/KafkaClientsConfigurationBuilder.cs" "$kafka/KafkaConsumerConfigurationBuilder.cs" "$kafka/KafkaProducerConfigurationBuilder.cs"

echo "### Schema registry"
compare "$schema_registry/_autogenerated.cs" "$schema_registry/KafkaSchemaRegistryConfigurationBuilder.cs"
